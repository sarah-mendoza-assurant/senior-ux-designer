#!/usr/bin/env python3
"""Import the official criteria from the Excel workbook into data/criteria.json.

Standard library only. The workbook is opened read-only and never modified.

Usage:
    python3 scripts/import_workbook.py /path/to/Job_Levels_and_Expectations-Sarah.xlsx

Column mapping on the "Role Expecation" worksheet (wording is preserved verbatim):
    B = Activity            C = Sr UXD expectation     D = UXD expectation
    E = historical "Sarah Feedback" (prior-year self-rating)
    F = historical notes    (F2/G2 hold the mastery-scale key)
Category rows are rows that have text in column B only.
"""
import json
import re
import sys
import zipfile
import xml.etree.ElementTree as ET
from pathlib import Path

NS = {"m": "http://schemas.openxmlformats.org/spreadsheetml/2006/main"}
Q = "{%s}" % NS["m"]
ROOT = Path(__file__).resolve().parent.parent

CATEGORY_IDS = {
    "UI": "ui",
    "UX": "ux",
    "Product Thinking": "pt",
    "Ownership/Approvals": "own",
    "Leadership": "lead",
    "Business Acumen and Communication": "biz",
    "Data and Metrics": "data",
}


def read_workbook(path):
    z = zipfile.ZipFile(path)
    shared = []
    for si in ET.fromstring(z.read("xl/sharedStrings.xml")).findall("m:si", NS):
        shared.append("".join(t.text or "" for t in si.iter(Q + "t")))

    wb = ET.fromstring(z.read("xl/workbook.xml"))
    names = [s.get("name") for s in wb.find("m:sheets", NS)]

    def sheet(n):
        cells = {}
        for c in ET.fromstring(z.read(f"xl/worksheets/sheet{n}.xml")).iter(Q + "c"):
            v = c.find("m:v", NS)
            if v is None:
                continue
            cells[c.get("r")] = shared[int(v.text)] if c.get("t") == "s" else v.text
        return cells

    return names, sheet(1), sheet(2)


def row_of(ref):
    return int(re.match(r"[A-Z]+(\d+)", ref).group(1))


def main(path):
    names, s1, s2 = read_workbook(path)
    rows = sorted({row_of(k) for k in s1})
    cat_counts, categories, current = {}, [], None

    for r in rows:
        if r <= 2:
            continue
        b = s1.get(f"B{r}")
        c, d, e, f = (s1.get(f"{col}{r}") for col in "CDEF")
        if b is None:
            continue
        if c is None and d is None and e is None and f is None:
            cid = CATEGORY_IDS[b]
            current = {"id": cid, "name": b, "sourceRow": r, "criteria": []}
            categories.append(current)
            continue
        lines = b.split("\n")
        n = len(current["criteria"]) + 1
        current["criteria"].append(
            {
                "id": f"{current['id']}-{n:02d}",
                "sourceRow": r,
                "activity": b,
                "title": lines[0],
                "description": "\n".join(lines[1:]),
                "srUxd": c,
                "uxd": d,
                "priorRating": e,
                "priorNotes": f,
            }
        )

    key_terms = s1.get("F2", "").split("\n")
    key_defs = s1.get("G2", "").split("\n")
    scale = [
        {"level": t.strip(), "meaning": m.strip()}
        for t, m in zip(key_terms, key_defs)
        if t.strip() and t.strip() != "KEY"
    ]

    data = {
        "_generated": "Generated by scripts/import_workbook.py. Do not hand-edit; re-run the import instead.",
        "source": {
            "worksheet": names[0],
            "title": s1.get("B1"),
            "columns": {
                "B": s1.get("B2"),
                "C": s1.get("C2"),
                "D": s1.get("D2"),
                "E": s1.get("E2"),
            },
            "priorRatingNote": "Prior ratings and notes were recorded approximately one year ago and are kept separate from current assessments.",
        },
        "masteryScale": scale,
        "categories": categories,
        "growthWorksheet": {
            "worksheet": names[1],
            "rows": [
                {"label": s2.get(f"A{r}"), "value": s2.get(f"B{r}")}
                for r in sorted({row_of(k) for k in s2})
            ],
        },
    }

    out = ROOT / "data" / "criteria.json"
    out.write_text(json.dumps(data, indent=2, ensure_ascii=False) + "\n", encoding="utf-8")
    total = sum(len(c["criteria"]) for c in categories)
    print(f"Wrote {out.relative_to(ROOT)}: {total} criteria in {len(categories)} categories")
    for c in categories:
        print(f"  {c['name']}: {len(c['criteria'])}")


if __name__ == "__main__":
    if len(sys.argv) != 2:
        sys.exit(__doc__)
    main(sys.argv[1])
